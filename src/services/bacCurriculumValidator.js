/**
 * 🔍 Deep Keyword Analyzer for Algerian BAC Curriculum
 * يفحص النص ويحدد درجة انتمائه لمنهاج البكالوريا والمادة المحتملة
 */
export function analyzeBacContent(rawText) {
  if (!rawText || rawText.trim().length < 15) {
    return {
      isValidBac: false,
      confidence: 0,
      matchedSubject: null,
      matchedKeywords: [],
      reason: 'النص قصير جداً أو فارغ لا يحتوي على محتوى دراسي كافٍ.'
    };
  }

  const normalizedText = rawText.toLowerCase().replace(/[\n\r\t]/g, ' ');
  let bestSubject = null;
  let maxMatches = 0;
  let allFoundKeywords = [];

  for (const [key, category] of Object.entries(BAC_CURRICULUM_LEXICON)) {
    let subjectMatches = 0;
    const foundInSubject = [];

    for (const kw of category.keywords) {
      if (normalizedText.includes(kw.toLowerCase())) {
        subjectMatches++;
        foundInSubject.push(kw);
      }
    }

    if (subjectMatches > maxMatches) {
      maxMatches = subjectMatches;
      bestSubject = category.name;
      allFoundKeywords = foundInSubject;
    }
  }

  // Also check general academic terms
  const generalAcademicTerms = [
    'درس', 'وحدة', 'ملخص', 'تمرين', 'حل', 'مسألة', 'بكالوريا', 'باك', '3as', 'السنة الثالثة',
    'تعريف', 'قانون', 'خاصية', 'علاقة', 'شعبة', 'علوم', 'رياضيات', 'تقني', 'اداب', 'لغات',
    'bac', 'exercice', 'solution', 'chapitre', 'cours', 'resumé', 'formule', 'theoreme'
  ];

  let generalMatches = 0;
  for (const genKw of generalAcademicTerms) {
    if (normalizedText.includes(genKw)) {
      generalMatches++;
    }
  }

  const totalScore = maxMatches * 2 + generalMatches;
  const isValidBac = totalScore >= 2 || maxMatches >= 1;

  return {
    isValidBac,
    confidence: totalScore,
    matchedSubject: bestSubject,
    matchedKeywords: allFoundKeywords.slice(0, 8),
    totalScore
  };
}
